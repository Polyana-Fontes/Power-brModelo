package games.polyclub.power.brmodelo.ui.clipboard

import androidx.compose.ui.graphics.ImageBitmap
import androidx.compose.ui.graphics.asSkiaBitmap
import org.jetbrains.skia.EncodedImageFormat
import org.jetbrains.skia.Image as SkiaImage

internal actual suspend fun encodeImageBitmapToPngBytes(bitmap: ImageBitmap): ByteArray? =
    try {
        val skiaImage = SkiaImage.makeFromBitmap(bitmap.asSkiaBitmap())
        skiaImage.encodeToData(EncodedImageFormat.PNG, 100)?.bytes
    } catch (_: Throwable) {
        null
    }
